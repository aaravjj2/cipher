CORE = Path(__file__).resolve().parent
ROOT = CORE.parent
DEFAULT_OUT = ROOT / "data" / "eod_best_strategy_options_lab"
ANALYSIS_START = date(2026, 1, 26)
RECENT_START = date(2026, 4, 25)


@dataclass(frozen=True, slots=True)
class StrategySignal:
    strategy_id: str
    strategy_name: str
    symbol: str
    day: str
    entry_time_et: str
    option_exit_time_et: str
    underlying_exit_time_et: str
    underlying_exit_reason: str
    underlying_raw_return_pct: float
    selection_checkpoint: str


@dataclass(slots=True)
class OptionTradeRow:
    strategy_id: str
    strategy_name: str
    symbol: str
    day: str
    underlying_exit_reason: str
    underlying_raw_return_pct: float
    bucket: str
    structure: str
    execution_model: str
    exit_policy: str
    entry_time_et: str
    exit_time_et: str
    long_contract: str | None
    long_expiration: str | None
    long_strike: float | None
    short_contract: str | None
    short_strike: float | None
    entry_debit: float | None
    exit_value: float | None
    fees_dollars: float | None
    risk_capital_dollars: float | None
    pnl_dollars: float | None
    return_on_risk_pct: float | None
    status: str
    skip_reason: str | None


@dataclass(slots=True)
class VariantResult:
    strategy_id: str
    strategy_name: str
    symbol: str
    bucket: str
    structure: str
    execution_model: str
    exit_policy: str
    signal_n: int
    executed_n: int
    coverage_pct: float | None
    mean_return_pct: float | None
    median_return_pct: float | None
    trimmed_mean_pct: float | None
    win_rate_pct: float | None
