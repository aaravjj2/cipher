"""Translate the two locked EOD ETF strategies into historical option outcomes.

The underlying rules are generated by ``eod_best_strategy_lab`` and remain
unchanged. This module maps each underlying entry/exit into the targeted Alpaca
historical options archive and evaluates:

* 0DTE, front, weekly, and swing expiration buckets;
* ATM calls, approximately 0.75% OTM calls, and ATM/OTM vertical call spreads;
* base, worse, and severe execution models.

Execution is deliberately conservative: long legs enter at the observed minute
high plus modeled slippage and exit at the observed minute low minus modeled
slippage. Vertical legs are reconstructed independently with rational payoff
bounds. Per-contract fees are included. Five-minute underlying target/stop bars
are translated to the first option minute after the five-minute bar closes, so
no option price from before the underlying trigger is used.

Research only. No order-routing or paper-trading code is present.
"""
